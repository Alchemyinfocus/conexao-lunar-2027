const {runInContext}=require('node:vm');
const { JSDOM } = require('jsdom');
const { readFileSync } = require('node:fs');
const assert = require('node:assert/strict');
const html=readFileSync('index.html','utf8');
function setup(saved={}) {
 const dom=new JSDOM(html,{url:'https://planner.example/#diario',runScripts:'outside-only'});
 const w=dom.window; const d=w.document;
 w.scrollTo=()=>{};
 for(const [k,v] of Object.entries(saved))w.localStorage.setItem(k,v);
 for(const s of d.querySelectorAll('script:not([defer])')) runInContext(s.src?readFileSync(s.getAttribute('src'),'utf8'):s.textContent,dom.getInternalVMContext());
 for(const s of d.querySelectorAll('script[defer]')) runInContext(readFileSync(s.getAttribute('src'),'utf8'),dom.getInternalVMContext());
 d.dispatchEvent(new w.Event('DOMContentLoaded'));
 return w;
}
(async()=>{
 const w=setup();
 const d=w.document;
 const get=s=>d.querySelector(s);
 const click=s=>get(s).click();
 const text=s=>get(s).textContent;
 const set=(s,v,e)=>{get(s).value=v;get(s).dispatchEvent(new w.Event(e));};
 const language='alchemy-lunar-2027:language';
 assert.match(text('#diary-title'),/Meu Diário/);
 click('#lang-en');
 assert.match(text('#diary-title'),/My Lunar Journal/);
 assert.match(text('#diary-day-label'),/January/);
 assert.match(get('#diary-entry').placeholder,/How do I feel/);
 set('#diary-entry','Minha nota','input');
 click('#lang-pt');
 assert.equal(get('#diary-entry').value,'Minha nota');
 assert.match(text('#diary-save-status'),/Nota salva/);
 click('#lang-en');
 assert.match(text('#diary-save-status'),/Note saved/);
 click('.rebuild-feature-grid [data-feature=planning]');
 assert.match(text('#planning-title'),/Lunar Planning/);
 assert.equal(get('#planning-month').options[2].text,'March');
 set('#planning-month','2','change');
 set('#planning-intentions','Minha intenção','input');
 get('#planning-new-task').value='Minha tarefa';
 get('#planning-add-form').dispatchEvent(new w.Event('submit',{cancelable:true}));
 click('#planning-task-list input');
 assert.equal(text('#planning-progress'),'1 of 1 tasks completed');
 click('#lang-pt');
 assert.equal(text('#planning-progress'),'1 de 1 tarefas concluídas');
 assert.equal(get('#planning-month').value,'2');
 assert.equal(get('#planning-intentions').value,'Minha intenção');
 assert.match(text('#planning-task-list'),/Minha tarefaExcluir/);
 click('#lang-en');
 click('.rebuild-feature-grid [data-feature=settings]');
 set('#settings-timezone','Europe/London','change');
 assert.equal(text('#settings-timezone-status'),'Current time zone: London.');
 assert.match(text('#backup-safety-status'),/Your entries/);
 assert.equal(get('#settings-timezone').value,'Europe/London');
 const messages=[];
 w.alert=message=>messages.push(message);
 w.confirm=message=>{messages.push(message);return true};
 const file=get('#restore');
 Object.defineProperty(file,'files',{value:[{size:20,text:async()=>'{broken'}],configurable:true});
 await file.onchange({target:file});
 assert.deepEqual(messages,['Restore failed: Invalid JSON']);
 let exported;
 w.URL.createObjectURL = blob => { exported = blob; return 'blob:planner-test'; };
 w.URL.revokeObjectURL = () => {};
 w.HTMLAnchorElement.prototype.click = () => {};
 click('#settings-backup');
 assert.ok(exported, 'Export must produce a backup file');
 const reader = new w.FileReader();
 const serialized = await new Promise((resolve, reject) => {
   reader.onload = () => resolve(reader.result);
   reader.onerror = () => reject(reader.error);
   reader.readAsText(exported);
 });
 const backup = JSON.parse(serialized);
 const [noteKey] = Object.keys(backup.notes);
 const planKey = 'alchemy-lunar-2027:planning:03';
 assert.equal(backup.notes[noteKey], 'Minha nota');
 assert.equal(backup.planning[planKey].tasks[0].done, true);
 w.localStorage.removeItem(noteKey);
 w.localStorage.removeItem(planKey);
 Object.defineProperty(file, 'files', {
   value: [{size: serialized.length, text: async () => serialized}], configurable: true
 });
 await file.onchange({target: file});
 assert.match(messages[1], /Restore 1 notes and 1 months of planning/);
 assert.equal(messages[2], 'Backup restored successfully.');
 assert.equal(w.localStorage.getItem(noteKey), 'Minha nota');
 assert.equal(JSON.parse(w.localStorage.getItem(planKey)).intentions, 'Minha intenção');
 const saved=Object.fromEntries(Object.entries(w.localStorage));
 assert.equal(saved[language],'en');
 const reload=setup(saved);
 assert.match(reload.document.querySelector('#diary-title').textContent,/My Lunar Journal/);
 assert.equal(reload.document.querySelector('#diary-entry').value,'Minha nota');
 assert.equal(reload.document.querySelector('#settings-timezone-status').textContent,'Current time zone: London.');
 click('#lang-pt');
 assert.equal(text('#settings-timezone-status'),'Fuso atual: Londres.');
 assert.match(text('#backup-safety-status'),/Atenção/);
 for(const el of d.querySelectorAll('[data-lunar-text],[data-lunar-placeholder]')){
   const key=el.dataset.lunarText||el.dataset.lunarPlaceholder;
   for(const locale of ['pt','en']) assert.ok(w.LunarI18n.translations[locale][key],key);
 }
 console.log('PT/EN, reload, note and plan data, tasks, time zone, backup export, restore, and invalid backup passed.');
 w.close();
 reload.close();
})().catch(e=>{console.error(e);process.exitCode=1});
